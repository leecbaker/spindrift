    #[test]
    fn numeric_static_offset_uses_final_collapsed_track_lines() {
        let placement = css::GridPlacement::Line(css::GridLinePlacement {
            name: None,
            index: Some(3),
        });
        let tracks = css::GridTrackList::Tracks {
            components: vec![css::GridTrackListComponent::Repeat(
                Vec::new(),
                css::GridRepeat {
                    count: css::GridRepeatCount::AutoFit,
                    tracks: vec![css::GridTrackListComponent::Track(
                        Vec::new(),
                        css::GridTrackSize {
                            min: css::GridMinTrackBreadth::LengthPercentage(
                                css::ComputedLengthPercentage::from_points(20.0),
                            ),
                            max: css::GridMaxTrackBreadth::LengthPercentage(
                                css::ComputedLengthPercentage::from_points(20.0),
                            ),
                        },
                    )],
                    trailing_names: Vec::new(),
                },
            )],
            trailing_names: Vec::new(),
        };
        assert_eq!(
            grid_layout_line_static_offset(
                &tracks,
                &css::GridAutoTrackList::initial(),
                &placement,
                &[0.0, 25.0, 45.0, 45.0],
                css::ComputedGap::LengthPercentage(css::ComputedLengthPercentage::from_points(5.0),),
                css::ContentAlignment::new(css::ContentAlignmentKeyword::Start),
                70.0,
            ),
            Some(45.0)
        );
        assert_eq!(
            grid_layout_line_static_offset(
                &tracks,
                &css::GridAutoTrackList::initial(),
                &placement,
                &[0.0, 25.0, 45.0, 45.0],
                css::ComputedGap::LengthPercentage(css::ComputedLengthPercentage::from_points(5.0),),
                css::ContentAlignment::new(css::ContentAlignmentKeyword::End),
                70.0,
            ),
            Some(70.0)
        );
        assert_eq!(
            grid_layout_line_static_offset(
                &tracks,
                &css::GridAutoTrackList::initial(),
                &placement,
                &[0.0, 25.0, 45.0, 45.0],
                css::ComputedGap::LengthPercentage(css::ComputedLengthPercentage::from_points(5.0),),
                css::ContentAlignment::new(css::ContentAlignmentKeyword::SpaceBetween),
                70.0,
            ),
            Some(70.0)
        );
        let space_around = grid_layout_line_static_offset(
            &tracks,
            &css::GridAutoTrackList::initial(),
            &placement,
            &[0.0, 25.0, 45.0, 45.0],
            css::ComputedGap::LengthPercentage(css::ComputedLengthPercentage::from_points(5.0)),
            css::ContentAlignment::new(css::ContentAlignmentKeyword::SpaceAround),
            70.0,
        )
        .unwrap();
        assert!(
            (space_around - 63.75).abs() < 0.001,
            "space-around should add half edge interval plus one between interval: {space_around}"
        );
        let space_evenly = grid_layout_line_static_offset(
            &tracks,
            &css::GridAutoTrackList::initial(),
            &placement,
            &[0.0, 25.0, 45.0, 45.0],
            css::ComputedGap::LengthPercentage(css::ComputedLengthPercentage::from_points(5.0)),
            css::ContentAlignment::new(css::ContentAlignmentKeyword::SpaceEvenly),
            70.0,
        )
        .unwrap();
        assert!(
            (space_evenly - (45.0 + 25.0 / 3.0 * 2.0)).abs() < 0.001,
            "space-evenly should add one edge interval and one between interval: {space_evenly}"
        );
    }

