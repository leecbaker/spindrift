fn grid_track_list_has_auto_repeat(tracks: &css::GridTrackList) -> bool {
    let css::GridTrackList::Tracks { components, .. } = tracks else {
        return false;
    };
    components.iter().any(grid_track_component_has_auto_repeat)
}

pub(super) fn grid_track_list_has_auto_fit(tracks: &css::GridTrackList) -> bool {
    let css::GridTrackList::Tracks { components, .. } = tracks else {
        return false;
    };
    components.iter().any(grid_track_component_has_auto_fit)
}

fn grid_track_component_has_auto_repeat(component: &css::GridTrackListComponent) -> bool {
    let css::GridTrackListComponent::Repeat(_, repeat) = component else {
        return false;
    };
    matches!(
        repeat.count,
        css::GridRepeatCount::AutoFill | css::GridRepeatCount::AutoFit
    )
}

fn grid_track_component_has_auto_fit(component: &css::GridTrackListComponent) -> bool {
    let css::GridTrackListComponent::Repeat(_, repeat) = component else {
        return false;
    };
    matches!(repeat.count, css::GridRepeatCount::AutoFit)
}

fn auto_repeat_explicit_line_names(
    tracks: &css::GridTrackList,
    auto_repeat_count: u16,
) -> Option<Vec<Vec<String>>> {
    let css::GridTrackList::Tracks {
        components,
        trailing_names,
    } = tracks
    else {
        return None;
    };
    let mut lines = Vec::new();
    let mut current_line_names = Vec::new();
    collect_auto_repeat_line_names(
        components,
        auto_repeat_count,
        &mut current_line_names,
        &mut lines,
    )?;
    current_line_names.extend(trailing_names.iter().cloned());
    lines.push(current_line_names);
    Some(lines)
}

fn auto_repeat_explicit_track_sizes(
    tracks: &css::GridTrackList,
    auto_repeat_count: u16,
    container_size: f32,
) -> Option<Vec<f32>> {
    let components = grid_track_list_components(tracks)?;
    let mut sizes = Vec::new();
    collect_auto_repeat_track_sizes(components, auto_repeat_count, container_size, &mut sizes)?;
    Some(sizes)
}

fn collect_auto_repeat_track_sizes(
    components: &[css::GridTrackListComponent],
    auto_repeat_count: u16,
    container_size: f32,
    sizes: &mut Vec<f32>,
) -> Option<()> {
    for component in components {
        match component {
            css::GridTrackListComponent::Track(_, size) => {
                sizes.push(definite_auto_repeat_track_size(
                    size.clone(),
                    container_size,
                )?);
            }
            css::GridTrackListComponent::Repeat(_, repeat) => {
                let count = match repeat.count {
                    css::GridRepeatCount::Number(count) => count,
                    css::GridRepeatCount::AutoFill | css::GridRepeatCount::AutoFit => {
                        auto_repeat_count
                    }
                };
                for _ in 0..count {
                    collect_auto_repeat_track_sizes(
                        &repeat.tracks,
                        auto_repeat_count,
                        container_size,
                        sizes,
                    )?;
                }
            }
        }
    }
    Some(())
}

fn line_offsets_from_track_sizes(track_sizes: &[f32], gap: f32) -> Vec<f32> {
    let mut offsets = Vec::with_capacity(track_sizes.len() + 1);
    let mut offset = 0.0;
    offsets.push(offset);
    for (index, size) in track_sizes.iter().enumerate() {
        offset += *size;
        if index + 1 < track_sizes.len() {
            offset += gap;
        }
        offsets.push(offset);
    }
    offsets
}

struct AutoRepeatStaticLineOffsets {
    first_line_index: i32,
    offsets: Vec<f32>,
}

impl AutoRepeatStaticLineOffsets {
    fn offset_index(&self, line_index: i32) -> Option<usize> {
        usize::try_from(line_index.checked_sub(self.first_line_index)?).ok()
    }
}

fn auto_repeat_static_line_offsets(
    line_offsets: &[f32],
    line_names: &[Vec<String>],
    auto_tracks: &css::GridAutoTrackList,
    line_index: i32,
    gap: css::ComputedGap,
    container_size: f32,
) -> Option<AutoRepeatStaticLineOffsets> {
    let explicit_line_count = i32::try_from(line_names.len()).ok()?;
    let before_track_count = if line_index < 1 {
        usize::try_from(1_i32.checked_sub(line_index)?).ok()?
    } else {
        0
    };
    let after_track_count = if line_index > explicit_line_count {
        usize::try_from(line_index.checked_sub(explicit_line_count)?).ok()?
    } else {
        0
    };
    let gap = definite_grid_gap_size(gap, layout_pt(container_size)).points();
    if before_track_count == 0 && after_track_count == 0 {
        return Some(AutoRepeatStaticLineOffsets {
            first_line_index: 1,
            offsets: line_offsets.to_vec(),
        });
    }

    let mut offsets = line_offsets.to_vec();
    let mut first_line_index = 1;
    if before_track_count > 0 {
        let mut expanded = Vec::with_capacity(before_track_count + offsets.len());
        let mut offset = 0.0;
        expanded.push(offset);
        for auto_index in (0..before_track_count).rev() {
            offset +=
                cycled_definite_auto_track_size_before(auto_tracks, auto_index, container_size)?;
            offset += gap;
            expanded.push(offset);
        }
        let explicit_start_offset = offset;
        expanded.extend(
            offsets
                .iter()
                .skip(1)
                .map(|line_offset| explicit_start_offset + *line_offset),
        );
        offsets = expanded;
        first_line_index = 1_i32.checked_sub(i32::try_from(before_track_count).ok()?)?;
    }
    if after_track_count > 0 {
        let mut offset = offsets.last().cloned()?;
        for auto_index in 0..after_track_count {
            // A following implicit line is after the preceding gutter and
            // track. The next gutter is before the next implicit track, not
            // part of this line's offset.
            offset += gap;
            offset +=
                cycled_definite_auto_track_size_after(auto_tracks, auto_index, container_size)?;
            offsets.push(offset);
        }
    }
    let result = AutoRepeatStaticLineOffsets {
        first_line_index,
        offsets,
    };
    result
        .offset_index(line_index)
        .and_then(|index| result.offsets.get(index))
        .cloned()?;
    Some(result)
}

fn collect_auto_repeat_line_names(
    components: &[css::GridTrackListComponent],
    auto_repeat_count: u16,
    current_line_names: &mut Vec<String>,
    lines: &mut Vec<Vec<String>>,
) -> Option<()> {
    for component in components {
        match component {
            css::GridTrackListComponent::Track(names, _) => {
                current_line_names.extend(names.iter().cloned());
                lines.push(std::mem::take(current_line_names));
            }
            css::GridTrackListComponent::Repeat(names, repeat) => {
                current_line_names.extend(names.iter().cloned());
                let count = match repeat.count {
                    css::GridRepeatCount::Number(count) => count,
                    css::GridRepeatCount::AutoFill | css::GridRepeatCount::AutoFit => {
                        auto_repeat_count
                    }
                };
                for _ in 0..count {
                    collect_auto_repeat_line_names(
                        &repeat.tracks,
                        auto_repeat_count,
                        current_line_names,
                        lines,
                    )?;
                    current_line_names.extend(repeat.trailing_names.iter().cloned());
                }
            }
        }
    }
    Some(())
}

